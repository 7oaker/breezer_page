#!/usr/bin/env node
/**
 * Copies the words printed on the store images from react_Breezer/aso/screens-copy/
 * <lang>.json into src/data/storeShots.ts (the region between the COPY markers).
 *
 *   npm run sync:store-copy        (reads ../react_Breezer, or $BREEZER_APP_DIR)
 *
 * All store wording lives in react_Breezer/aso/: the listing texts as Markdown,
 * the image headlines as JSON, so one review covers every word that reaches a
 * store. This repo only renders them. The region is rewritten as a whole and
 * checked: every language needs every headline, exactly one *accent* at the end.
 */

import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';

const APP_DIR = resolve(process.env.BREEZER_APP_DIR ?? '../react_Breezer');
const SRC = `${APP_DIR}/aso/screens-copy`;
const TARGET = new URL('../src/data/storeShots.ts', import.meta.url).pathname;
const ORDER = ['en', 'de', 'it', 'pl', 'sv', 'no', 'cs', 'sk', 'sl', 'hr', 'da', 'fi', 'hu'];
const FRAMES = ['press', 'stats', 'quit', 'widgets', 'community', 'ranking', 'games', 'journey', 'health', 'craving', 'chat', 'goals', 'merch'];

const problems = [];
const checkLine = (where, s) => {
  if (typeof s !== 'string' || !s.trim()) return problems.push(`${where}: missing`);
  const accents = s.match(/\*[^*]+\*/g) ?? [];
  if (accents.length !== 1) problems.push(`${where}: needs exactly one *accent*, has ${accents.length}`);
  else if (!s.trim().endsWith('*')) problems.push(`${where}: the accent must close the line`);
  if (/[—–]/.test(s)) problems.push(`${where}: em or en dash`);
};

const files = readdirSync(SRC).filter((f) => f.endsWith('.json'));
const copy = {};
for (const lang of ORDER) {
  if (!files.includes(`${lang}.json`)) continue;
  const c = JSON.parse(readFileSync(`${SRC}/${lang}.json`, 'utf8'));
  for (const f of FRAMES) checkLine(`${lang}.headlines.${f}`, c.headlines?.[f]);
  for (const [page, frames] of Object.entries(c.overrides ?? {})) for (const [f, s] of Object.entries(frames)) checkLine(`${lang}.overrides.${page}.${f}`, s);
  for (const p of ['default', 'track', 'quit']) checkLine(`${lang}.promo.${p}`, c.promo?.[p]);
  for (const p of ['track', 'quit']) if (!c.labels?.[p]) problems.push(`${lang}.labels.${p}: missing`);
  if (!c.motion?.together) problems.push(`${lang}.motion.together: missing (the video's third word, next to the labels)`);
  copy[lang] = c;
}

if (problems.length) {
  console.error(`✗ ${problems.length} problem(s), storeShots.ts unchanged:\n  ${problems.join('\n  ')}`);
  process.exit(1);
}

const body = `export const COPY: Partial<Record<Lang, Copy>> = ${JSON.stringify(copy, null, 2)};`;
const src = readFileSync(TARGET, 'utf8');
const start = src.indexOf('// <copy>');
const end = src.indexOf('// </copy>');
if (start === -1 || end === -1) throw new Error('storeShots.ts has no // <copy> ... // </copy> region');
const out = `${src.slice(0, start)}// <copy> generated by scripts/sync-store-copy.mjs from react_Breezer/aso/screens-copy/, do not edit here\n${body}\n${src.slice(end)}`;
writeFileSync(TARGET, out);
console.log(`storeShots.ts: headlines for ${Object.keys(copy).join(', ')}`);
